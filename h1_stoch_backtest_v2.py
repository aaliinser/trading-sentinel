SYMBOLS = [
    "USDJPY=X", "EURAUD=X", "USDCHF=X", "EURCAD=X", "CADJPY=X",
    "GBPUSD=X", "USDCAD=X", "AUDNZD=X", "EURGBP=X", "EURUSD=X"
]

TIMEFRAME = "1h"
PERIOD_LIMIT = "2y" 
BREAK_EVEN_WR = 0.5263 

# --- STRATEGY PARAMETERS (OPTIMIZED FOR LIVE TRADING) ---
# Stochastic Settings
STOCH_K_PERIOD = 14      
STOCH_D_PERIOD = 3       
OVERBOUGHT_LEVEL = 80    # Expanded range for better sample size
OVERSOLD_LEVEL = 20      # Expanded range for better sample size

# Bollinger Bands Settings (New Addition)
BB_PERIOD = 20           # Standard period for BB calculation
BB_STD_DEV = 2.0         # Standard deviation multiplier

# Trend & Cost Settings
EMA_TREND_PERIOD = 200   
SPREAD_COST_PIPS = 2.0   

def flatten_columns(df):
    if isinstance(df.columns, pd.MultiIndex):
        df.columns = [col[0] for col in df.columns]
    return df

def get_data(symbol, period=PERIOD_LIMIT, interval=TIMEFRAME):
    """Fetches OHLCV data with strict gap validation."""
    try:
        ticker = yf.Ticker(symbol)
        df = ticker.history(period=period, interval=interval)
        if df.empty: 
            return None
        
        df = flatten_columns(df)
        required_cols = ['Open', 'High', 'Low', 'Close']
        if not all(col in df.columns for col in required_cols): 
            return None
            
        df = df.dropna(subset=['Close'])
        df.sort_index(inplace=True)
        
        # ★★ GAP HANDLING: Remove duplicate indices and ensure continuity
        df = df[~df.index.duplicated(keep='first')]
        
        if len(df) < 250:
            return None
            
        return df[['Open', 'High', 'Low', 'Close']]
    except Exception as e:
        print(f"Error fetching {symbol}: {e}")
        return None

def calculate_hybrid_indicators(df):
    """
    ★★ CORRECT MATHEMATICAL IMPLEMENTATION OF SLOW STOCHASTICS + BOLLINGER BANDS ★★
    Matches MT4/MT5/Broker algorithms exactly using Wilder's Smoothing Method.
    Adds Bollinger Bands as spatial filters for reversal points.
    """
    c = df['Close']
    h = df['High']
    l = df['Low']
    
    # 1. Calculate Raw Fast Stochastic %K
    lowest_low = l.rolling(window=STOCH_K_PERIOD).min()
    highest_high = h.rolling(window=STOCH_K_PERIOD).max()
    
    denom = highest_high - lowest_low
    denom.replace(0, np.nan, inplace=True) 
    
    raw_k = 100 * ((c - lowest_low) / denom)
    raw_k = raw_k.fillna(50) # Neutral fill for flat markets
    
    # 2. Apply Wilder's Smoothing to get Slow %K
    slow_k = raw_k.ewm(alpha=1/STOCH_D_PERIOD, adjust=False).mean()
    
    # 3. Calculate %D as Simple Moving Average of Slow %K
    stoch_d = slow_k.rolling(window=STOCH_D_PERIOD).mean()
    
    # Fill initial NaNs generated by rolling/EWM
    slow_k = slow_k.bfill().ffill()
    stoch_d = stoch_d.bfill().ffill()
    
    # 4. Exponential Moving Average (Trend Filter)
    ema_200 = c.ewm(span=EMA_TREND_PERIOD, adjust=False).mean()
    
    # 5. NEW: Calculate Bollinger Bands (Spatial Filter)
    sma_bb = c.rolling(window=BB_PERIOD).mean()
    std_bb = c.rolling(window=BB_PERIOD).std(ddof=0)
    bb_upper = sma_bb + (BB_STD_DEV * std_bb)
    bb_lower = sma_bb - (BB_STD_DEV * std_bb)
    
    return df.assign(
        STOC_SLOW_K=slow_k,
        STOC_D=stoch_d,
        EMA_200=ema_200,
        BB_UPPER=bb_upper,
        BB_LOWER=bb_lower
    )

def run_backtest_v3(df, symbol_name): 
    """
    Executes STRICT ENTRY RULES v3.0 (HYBRID LOGIC):
    CALL: Close > EMA200 AND Low touches/crosses BB_Lower AND Stoch_K < OVERSOLD_LEVEL
    PUT:  Close < EMA200 AND High touches/crosses BB_Upper AND Stoch_K > OVERBOUGHT_LEVEL
    
    Includes SPREAD COST MODELING for realistic P&L calculation.
    """
    trades = []
    timestamps = []
    n = len(df)
    
    # Start after indicators are stable (considering longest lookback)
    start_idx = max(STOCH_K_PERIOD, STOCH_D_PERIOD, EMA_TREND_PERIOD, BB_PERIOD) + 1
    
    # ★★ تحديد المعامل بناءً على اسم الزوج المُمرر الآن بشكل صحيح ★★
    pip_mult = 100.0 if "JPY" in symbol_name else 10000.0
    
    for i in range(start_idx, n - 1):
        curr_close = df['Close'].iloc[i]
        next_close = df['Close'].iloc[i+1]
        timestamp = df.index[i]
        
        # Get current values
        k_curr = df['STOC_SLOW_K'].iloc[i]
        ema_200 = df['EMA_200'].iloc[i]
        low_curr = df['Low'].iloc[i]
        high_curr = df['High'].iloc[i]
        bb_lower = df['BB_LOWER'].iloc[i]
        bb_upper = df['BB_UPPER'].iloc[i]
        
        direction = 0 # 0=None, 1=CALL, -1=PUT
        
        # --- BUY RULE (CALL) - HYBRID ---
        # Condition 1: Uptrend Context (Price above long-term average)
        # Condition 2: Spatial Touch (Price hit the lower volatility boundary)
        # Condition 3: Momentum Extreme (Stochastic confirms oversold condition)
        if curr_close > ema_200 and low_curr <= bb_lower and k_curr < OVERSOLD_LEVEL:
            direction = 1
            
        # --- SELL RULE (PUT) - HYBRID ---
        # Condition 1: Downtrend Context (Price below long-term average)
        # Condition 2: Spatial Touch (Price hit the upper volatility boundary)
        # Condition 3: Momentum Extreme (Stochastic confirms overbought condition)
        elif curr_close < ema_200 and high_curr >= bb_upper and k_curr > OVERBOUGHT_LEVEL:
            direction = -1
            
        if direction != 0:
            # Calculate Gross Profit/Loss in Price Difference
            price_diff = next_close - curr_close
            
            # Determine Win/Loss considering Spread Cost
            # We convert spread from Pips to Price units based on the pair type
            spread_in_price = SPREAD_COST_PIPS / pip_mult
            
            net_profitable = False
            
            if direction == 1: # CALL
                # Need price rise greater than spread cost
                net_profitable = price_diff > spread_in_price
                
            else: # PUT
                # Need price drop magnitude greater than spread cost
                net_profitable = (-price_diff) > spread_in_price
            
            trades.append(net_profitable)
            timestamps.append(timestamp)
            
    return trades, timestamps

def analyze_results(all_trades, all_timestamps):
    total = len(all_trades)
    if total == 0:
        return {'count': 0, 'wr': 0, 'z_score': 0, 'robust': 'N/A', 'wr_h1': 0, 'wr_h2': 0}
        
    wins = sum(all_trades)
    wr = wins / total
    
    p_null = BREAK_EVEN_WR
    std_dev = np.sqrt(total * p_null * (1 - p_null))
    z_score = (wins - (total * p_null)) / std_dev if std_dev > 0 else 0
    
    mid_point = total // 2
    h1_trades = all_trades[:mid_point]
    h2_trades = all_trades[mid_point:]
    
    wr_h1 = sum(h1_trades) / len(h1_trades) if h1_trades else 0
    wr_h2 = sum(h2_trades) / len(h2_trades) if h2_trades else 0
    
    is_robust = (wr_h1 >= BREAK_EVEN_WR) and (wr_h2 >= BREAK_EVEN_WR)
    robust_status = "PASS ✅" if is_robust else "FAIL ❌"
    
    return {
        'count': total, 
        'wr': wr, 
        'z_score': z_score, 
        'robust': robust_status,
        'wr_h1': wr_h1,
        'wr_h2': wr_h2
    }

